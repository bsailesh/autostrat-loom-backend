"""
Intermediate structure -> .docx bytes.

Builds against the reference template (template.docx, generated by
build_template.py) rather than defining styles programmatically -- see
word_export_briefing.md, "python-docx gotchas".

Memory shape matters here: the production instance has 414MB RAM
(word_export_briefing.md, "Memory constraint"). `ExportBuilder.add_report`
takes raw markdown and parses + renders it internally so the caller never
holds more than one report's parsed structure alongside the growing
document -- the parsed structure for report N is garbage-collectable before
report N+1 is even read from the database cursor.
"""
from __future__ import annotations

import logging
import pathlib

from docx import Document
from docx.enum.section import WD_ORIENT, WD_SECTION
from docx.enum.text import WD_ALIGN_PARAGRAPH, WD_BREAK, WD_COLOR_INDEX
from docx.opc.constants import RELATIONSHIP_TYPE
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Inches, Pt, RGBColor

from app.export import exhibits
from app.export.markdown_parser import (
    BulletListBlock,
    ExhibitBlock,
    Heading,
    HorizontalRule,
    KeyInsightsBox,
    Paragraph,
    Run,
    SCQABlock,
    TableBlock,
    parse_report,
)

logger = logging.getLogger(__name__)

TEMPLATE_PATH = pathlib.Path(__file__).parent / "template.docx"

_USABLE_WIDTH_PORTRAIT_IN = 6.5  # 8.5in page - 1in margins each side
_USABLE_WIDTH_LANDSCAPE_IN = 9.0  # 11in page - 1in margins each side

_RING_SHADES = ["D9E4F0", "C7D8EA", "B4CCE3"]  # TAM -> SAM -> SOM, progressively deeper
_HEADER_SHADE = "DCE6F1"
_KEY_INSIGHT_SHADE = "F0F4F8"
_SCQA_SHADE = "EEF2F7"
_SCQA_ANSWER_SHADE = "DCE6F1"
_FALLBACK_SHADE = "F5F5F5"
_FALLBACK_BORDER = "BFBFBF"

_SYMBOL_FONT = "Segoe UI Symbol"  # explicit, run-level -- box-drawing/Harvey Ball glyph coverage
_ACCENT = RGBColor(0x1F, 0x3A, 0x5F)


# ---------------------------------------------------------------------------
# Low-level OOXML helpers (python-docx has no API for these)
