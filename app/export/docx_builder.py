def _set_run_font(run, name: str) -> None:
    """Set a font on a run at the XML level (ascii/hAnsi/eastAsia/cs), not
    just `run.font.name` -- Word can otherwise substitute a different font
    for glyphs it buckets as "east asian" or "complex script", which is
    exactly the failure mode word_export_briefing.md calls out for the
    Harvey Ball and box-drawing glyphs. Must be set on the run, not inherited
    from a paragraph or table style.
    """
    run.font.name = name
    rPr = run._r.get_or_add_rPr()
    rFonts = rPr.find(qn("w:rFonts"))
    if rFonts is None:
        rFonts = OxmlElement("w:rFonts")
        rPr.append(rFonts)
    for attr in ("w:ascii", "w:hAnsi", "w:eastAsia", "w:cs"):
        rFonts.set(qn(attr), name)


def _shade_cell(cell, hex_color: str) -> None:
    """Cell background shading. `w:shd` needs `w:val="clear"` or it renders
    solid black instead of the intended fill (word_export_briefing.md)."""
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hex_color)
    tcPr.append(shd)


def _set_cell_borders(cell, hex_color: str) -> None:
    tcPr = cell._tc.get_or_add_tcPr()
    borders = OxmlElement("w:tcBorders")
    for edge in ("top", "left", "bottom", "right"):
        el = OxmlElement(f"w:{edge}")
        el.set(qn("w:val"), "single")
        el.set(qn("w:sz"), "4")
        el.set(qn("w:color"), hex_color)
        borders.append(el)
    tcPr.append(borders)


def _force_fixed_layout(table) -> None:
    """Explicit absolute widths only survive if the table layout is fixed --
    otherwise Word's autofit algorithm overrides them, which is why nested
    TAM/SAM/SOM tables collapse without this (word_export_briefing.md)."""
    table.autofit = False
    tblPr = table._tbl.tblPr
    layout = OxmlElement("w:tblLayout")
    layout.set(qn("w:type"), "fixed")
    tblPr.append(layout)


def _set_table_width(table, width_in: float, col_widths_in: list[float] | None = None) -> None:
    _force_fixed_layout(table)
    widths = col_widths_in or [width_in / max(1, len(table.columns))] * len(table.columns)
    for col, w in zip(table.columns, widths):
        col.width = Inches(w)
    for row in table.rows:
        for cell, w in zip(row.cells, widths):
            cell.width = Inches(w)


def _add_hyperlink(paragraph, url: str, text: str, *, bold: bool = False, italic: bool = False) -> None:
    """Insert a real Word hyperlink. python-docx has no API for this --
    standard raw-XML recipe: a relationship + a `w:hyperlink` element
    wrapping a run."""
    part = paragraph.part
    r_id = part.relate_to(url, RELATIONSHIP_TYPE.HYPERLINK, is_external=True)
    hyperlink = OxmlElement("w:hyperlink")
    hyperlink.set(qn("r:id"), r_id)

    new_run = OxmlElement("w:r")
    rPr = OxmlElement("w:rPr")
    color = OxmlElement("w:color")
    color.set(qn("w:val"), "1F3A5F")
    rPr.append(color)
    u = OxmlElement("w:u")
    u.set(qn("w:val"), "single")
    rPr.append(u)
    if bold:
        rPr.append(OxmlElement("w:b"))
    if italic:
        rPr.append(OxmlElement("w:i"))
    new_run.append(rPr)
    t = OxmlElement("w:t")
    t.set(qn("xml:space"), "preserve")
    t.text = text
    new_run.append(t)
    hyperlink.append(new_run)
    paragraph._p.append(hyperlink)


def _insert_toc_field(paragraph) -> None:
    """TOC is a field code -- no python-docx helper exists. Word populates
    it only when the user accepts the "update fields" prompt (or presses
    F9); that's expected and noted in the PR per word_export_briefing.md."""
    run = paragraph.add_run()
    r = run._r

    begin = OxmlElement("w:fldChar")
    begin.set(qn("w:fldCharType"), "begin")
    begin.set(qn("w:dirty"), "true")

    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = 'TOC \\o "1-2" \\h \\z \\u'

    separate = OxmlElement("w:fldChar")
    separate.set(qn("w:fldCharType"), "separate")

    placeholder = OxmlElement("w:t")
    placeholder.text = 'Right-click and choose "Update Field" to build the table of contents.'

    end = OxmlElement("w:fldChar")
    end.set(qn("w:fldCharType"), "end")

    for el in (begin, instr, separate, placeholder, end):
        r.append(el)


def _hr_paragraph(doc) -> None:
    """`---` -> a paragraph bottom border. Never a table (an explicit
    word_export_briefing.md gotcha)."""
    p = doc.add_paragraph()
    pPr = p._p.get_or_add_pPr()
    pBdr = OxmlElement("w:pBdr")
    bottom = OxmlElement("w:bottom")
    bottom.set(qn("w:val"), "single")
    bottom.set(qn("w:sz"), "6")
    bottom.set(qn("w:space"), "4")
    bottom.set(qn("w:color"), "C8C8C8")
    pBdr.append(bottom)
    pPr.append(pBdr)


def _set_repeat_header_row(table) -> None:
    """Repeat the table's first row as a header on every page it spans.
    No python-docx API for `w:tblHeader` -- raw XML on the row's `w:trPr`."""
    if not table.rows:
        return
    trPr = table.rows[0]._tr.get_or_add_trPr()
    header = OxmlElement("w:tblHeader")
    header.set(qn("w:val"), "true")
    trPr.append(header)


def _column_widths(headers: list[str], rows: list[list[str]], total_in: float) -> list[float]:
    """Weight column widths by how much content they actually carry, instead
    of splitting evenly (or always favoring column 0) -- a report's own
    tables vary wildly in shape: a "#" column of single digits next to a
    "Development" column of full sentences needs very different widths, and
    an even split (or a fixed "column 0 is the label" assumption) wraps the
    long column to many lines while the short one sits mostly empty.

    Each column's weight is the 75th-percentile string length across its
    header + cell values (not the max, so one unusually long cell doesn't
    dominate); a floor keeps a short column from collapsing to nothing.
    """
    n_cols = len(headers)
    if n_cols <= 1:
        return [total_in]

    def typical_length(c: int) -> float:
        values = [headers[c]] + [row[c] for row in rows if c < len(row)]
        lengths = sorted(len(v) for v in values) or [1]
        idx = min(len(lengths) - 1, int(len(lengths) * 0.75))
        return max(lengths[idx], len(headers[c]), 1)

    weights = [max(typical_length(c), 4) for c in range(n_cols)]
    widths = [total_in * w / sum(weights) for w in weights]
    floor = 0.5
    deficit = sum(max(0.0, floor - w) for w in widths)
    if deficit:
        widths = [max(floor, w) for w in widths]
        surplus_total = sum(w - floor for w in widths if w > floor)
        if surplus_total > 0:
            widths = [
                w - deficit * ((w - floor) / surplus_total) if w > floor else w for w in widths
            ]
    scale = total_in / sum(widths)
    return [w * scale for w in widths]


